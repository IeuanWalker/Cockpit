// A single queue orders parser writes, PTY resizes, reset and capture for each terminal.
// Detached terminals keep parsing output at their last size; remounting never replays it.
const terminals = new Map();
let assets;
function loadAssets() {
    return assets ??= (async () => {
        const css = document.createElement('link');
        css.rel = 'stylesheet';
        css.href = new URL('./vendor/xterm.css', import.meta.url).href;
        const ready = new Promise((resolve, reject) => { css.onload = resolve; css.onerror = reject; });
        document.head.append(css);
        for (const file of ['xterm.js', 'addon-fit.js', 'addon-serialize.js']) {
            await new Promise((resolve, reject) => {
                const script = document.createElement('script');
                script.src = new URL(`./vendor/${file}`, import.meta.url).href;
                script.onload = resolve; script.onerror = reject;
                document.head.append(script);
            });
        }
        await ready;
        await document.fonts.ready;
    })();
}
function enqueue(s, action) {
    const operation = s.queue.then(() => s.disposed ? undefined : action());
    s.queue = operation.catch(async error => {
        if (!s.disposed) {
            console.error('Terminal:', error);
            await s.dotnet.invokeMethodAsync('ReportError', String(error.message ?? error)).catch(() => {});
        }
    });
    return operation;
}
function write(s, data) {
    return data ? new Promise(resolve => s.term.write(data, resolve)) : Promise.resolve();
}
async function drain(s) {
    const output = await s.dotnet.invokeMethodAsync('TakeOutput');
    await write(s, output);
}
async function fit(s) {
    if (!s.host?.isConnected || s.host.clientWidth < 20 || s.host.clientHeight < 20) return;
    const size = s.fit.proposeDimensions();
    if (!size || !Number.isFinite(size.cols) || !Number.isFinite(size.rows)) return;
    const cols = Math.max(2, size.cols), rows = Math.max(1, size.rows);
    if (s.started && cols === s.term.cols && rows === s.term.rows) return;
    // Finish parsing old output first, then update the emulator BEFORE requesting shell
    // redraw. Shell output generated by the resize is only parsed at the new dimensions.
    await drain(s);
    s.term.resize(cols, rows);
    if (s.started) await s.dotnet.invokeMethodAsync('Resize', cols, rows);
    else {
        s.acceptInput = true;
        await s.dotnet.invokeMethodAsync('Start', cols, rows);
        s.started = true;
    }
    await drain(s);
    s.term.refresh(0, rows - 1);
}
function scheduleFit(s) {
    if (s.frame || s.disposed) return;
    s.frame = requestAnimationFrame(() => {
        s.frame = 0;
        if (s.fitQueued) { s.fitAgain = true; return; }
        s.fitQueued = true;
        enqueue(s, () => fit(s)).catch(() => {}).finally(() => {
            s.fitQueued = false;
            if (s.fitAgain) { s.fitAgain = false; scheduleFit(s); }
        });
    });
}
export async function attach(id, host, attachment, dotnet, transcript, cols, rows, windowsBuild) {
    if (!(host instanceof Element) || !host.isConnected) return;
    await loadAssets();
    if (!host.isConnected) return;
    let s = terminals.get(id);
    if (!s) {
        const term = new globalThis.Terminal({
            cols: Math.max(2, cols), rows: Math.max(1, rows), cursorBlink: true,
            fontSize: 13, fontFamily: "Consolas, 'Courier New', monospace",
            scrollback: 10000, allowProposedApi: true,
            // ConPTY also reflows its screen; use xterm's platform support to avoid
            // applying incompatible legacy Windows wrapping behavior.
            windowsPty: windowsBuild ? { backend: 'conpty', buildNumber: windowsBuild } : undefined,
            theme: { background: '#181818', foreground: '#dddddd', cursor: '#dddddd' }
        });
        s = { term, dotnet, queue: Promise.resolve(), inputQueue: Promise.resolve(), started: false };
        s.fit = new globalThis.FitAddon.FitAddon();
        s.serialize = new globalThis.SerializeAddon.SerializeAddon();
        term.loadAddon(s.fit); term.loadAddon(s.serialize);
        s.container = document.createElement('div');
        s.container.style.cssText = 'height:100%;width:100%;overflow:hidden;';
        host.append(s.container);
        term.open(s.container);
        term.onData(data => {
            if (s.acceptInput && !s.disposed)
                s.inputQueue = s.inputQueue.then(() => s.dotnet.invokeMethodAsync('Input', data))
                    .catch(error => s.dotnet.invokeMethodAsync('ReportError', String(error.message ?? error)));
        });
        terminals.set(id, s);
        await enqueue(s, async () => {
            if (transcript) {
                await write(s, transcript);
                await write(s, '\x1b[0m\r\n\r\n[Restored terminal output — starting a new shell]\r\n');
            }
        });
    }
    s.observer?.disconnect();
    s.host = host; s.attachment = attachment;
    host.append(s.container);
    s.observer = new ResizeObserver(() => scheduleFit(s));
    s.observer.observe(host);
    await enqueue(s, () => fit(s));
    if (host.isConnected) s.term.focus();
}
export function detach(id, attachment) {
    const s = terminals.get(id);
    if (!s || s.attachment !== attachment) return;
    s.observer?.disconnect();
    cancelAnimationFrame(s.frame); s.frame = 0;
    s.container.remove(); s.host = null;
}
export function focus(id) {
    const s = terminals.get(id);
    if (s?.host?.isConnected) { scheduleFit(s); s.term.focus(); }
}
export function flush(id) {
    const s = terminals.get(id);
    return s ? enqueue(s, () => drain(s)) : Promise.resolve();
}
export function reset(id) {
    const s = terminals.get(id);
    return s && enqueue(s, async () => {
        await s.inputQueue;
        s.acceptInput = false;
        s.term.reset();
        await s.dotnet.invokeMethodAsync('Restart', s.term.cols, s.term.rows);
        s.started = true; s.acceptInput = true;
        await drain(s);
        s.term.focus();
    });
}
export function snapshot(id) {
    const s = terminals.get(id);
    return s ? enqueue(s, async () => {
        await drain(s);
        return s.serialize.serialize({ scrollback: 10000, excludeAltBuffer: true, excludeModes: true });
    }) : '';
}
// Only remove a recognizable, idle prompt on the cursor's logical line. Ordinary
// final output must survive even when the process hasn't printed a newline yet.
export function isIdlePrompt(value) {
    return /^(?:PS(?:\s+.+)?>|[A-Za-z]:\\.*>|(?:\([^)]*\)\s*)?\S+@\S+.*[$#%]|(?:\S+[:/~].*?)?[$#%❯➜]|shell>)\s*$/.test(value.trim());
}
function terminalText(id, count, omitPrompt) {
    const s = terminals.get(id);
    return s ? enqueue(s, async () => {
        await drain(s);
        const buffer = s.term.buffer.active;
        const lines = [];
        let cursorLine = -1;
        for (let i = 0; i < buffer.length; i++) {
            const line = buffer.getLine(i);
            if (!line) continue;
            const content = line.translateToString(!buffer.getLine(i + 1)?.isWrapped);
            if (line.isWrapped && lines.length) lines[lines.length - 1] += content;
            else lines.push(content);
            if (i === buffer.baseY + buffer.cursorY) cursorLine = lines.length - 1;
        }
        while (lines.length && lines.at(-1) === '') lines.pop();
        if (omitPrompt) {
            if (lines.length && cursorLine === lines.length - 1 && isIdlePrompt(lines.at(-1))) lines.pop();
            while (lines.length && !lines.at(-1).trim()) lines.pop();
            while (lines.length && !lines[0].trim()) lines.shift();
        }
        const selected = lines.slice(-count);
        if (omitPrompt) while (selected.length && !selected[0].trim()) selected.shift();
        return selected.join('\n');
    }) : '';
}
export function text(id, count) { return terminalText(id, count, false); }
export function messageText(id, count) { return terminalText(id, count, true); }
export async function dispose(id) {
    const s = terminals.get(id);
    if (!s) return;
    detach(id, s.attachment);
    await s.queue;
    await s.inputQueue;
    s.disposed = true;
    s.term.dispose(); terminals.delete(id);
}

export function showDialog(element) { if (element instanceof HTMLDialogElement) element.showModal(); }
export function closeDialog(element) { if (element instanceof HTMLDialogElement) element.close(); }
